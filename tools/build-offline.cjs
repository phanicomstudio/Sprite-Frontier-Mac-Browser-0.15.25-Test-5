#!/usr/bin/env node
/* October 15, 2026 (0.15.27): builds offline/*.js, the generated asset bundles
 * that let the game run when index.html is opened straight from disk.
 *
 * Over http(s) the game loads PNG and GLB files directly and never needs these
 * bundles; they exist only because browsers block pixel/byte access to local
 * files. Each bundle holds byte-identical base64 data URIs keyed by site path,
 * installed into window.FrontierOfflineAssets. Bundle names follow
 * FrontierAssets.groupOf, read from src/asset-source.js itself.
 *
 * offline/ is generated and git-ignored. Run before packaging a double-click
 * (file-based) build:   npm run build:offline
 * Usage: node tools/build-offline.cjs [engine folder]   (default: this repo)
 */
"use strict";
const fs = require("node:fs"),
  path = require("node:path"),
  vm = require("node:vm");

const MIME = { ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".webp": "image/webp", ".glb": "model/gltf-binary" };

/* @function buildOffline.groupRule - Inputs: engine folder. Returns FrontierAssets.groupOf evaluated from that folder's src/asset-source.js in a sandbox (http mode, network stubbed), so the build and the runtime share one grouping rule. Throws if the loader cannot be evaluated. */
function groupRule(root) {
  const context = {
    location: { protocol: "http:" },
    /* @function buildOffline.noFetch - Inputs: ignored. Returns a promise that never settles; startup loading is irrelevant to the build. */
    fetch() {
      return new Promise(/* @function buildOffline.pending - Inputs: ignored resolve/reject. Never settles. */ function () {});
    },
  };
  context.globalThis = context;
  vm.runInNewContext(fs.readFileSync(path.join(root, "src/asset-source.js"), "utf8"), context);
  return context.FrontierAssets.groupOf;
}

/* @function buildOffline.catalogPaths - Inputs: engine folder and a catalog entry { script, field }. Returns every string value of that field found in the script (for example each "image" in outdoor-assets.js). Reads the script as text; never executes it. */
function catalogPaths(root, entry) {
  const text = fs.readFileSync(path.join(root, entry.script), "utf8");
  const pattern = new RegExp('"' + entry.field + '":\\s*"([^"]+)"', "g");
  return Array.from(text.matchAll(pattern), /* @function buildOffline.captured - Inputs: regex match. Returns the captured path. */ function (m) {
    return m[1];
  });
}

/* @function buildOffline.listAssets - Inputs: engine folder. Returns the sorted, de-duplicated list of site-relative paths named by tools/offline-manifest.json (explicit files, folder contents by extension, and catalog references). Throws naming the first missing file, so a stale manifest fails loudly. */
function listAssets(root) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, "tools/offline-manifest.json"), "utf8"));
  const paths = new Set(manifest.files);
  for (const folder of manifest.folders)
    for (const name of fs.readdirSync(path.join(root, folder.path)))
      if (folder.extensions.includes(path.extname(name).toLowerCase())) paths.add(folder.path + "/" + name);
  for (const entry of manifest.catalogs) for (const p of catalogPaths(root, entry)) paths.add(p);
  for (const p of paths) {
    if (p.includes("..") || path.isAbsolute(p)) throw Error("Unsafe asset path in manifest: " + p);
    if (!fs.statSync(path.join(root, p), { throwIfNoEntry: false })?.isFile()) throw Error("Offline manifest names a missing file: " + p);
    if (!MIME[path.extname(p).toLowerCase()]) throw Error("Unsupported offline asset type: " + p);
  }
  return Array.from(paths).sort();
}

/* @function buildOffline.build - Inputs: engine folder. Returns { bundles: { name: { files, bytes } } } describing what was written. Rebuilds offline/ from scratch: one script per group, each adding path → data URI entries to window.FrontierOfflineAssets. Writes to a temporary folder first and swaps it in, so a failed build never leaves a half-written offline/. */
function build(root) {
  root = path.resolve(root);
  const groupOf = groupRule(root);
  const groups = new Map();
  for (const p of listAssets(root)) {
    const name = groupOf(p);
    if (!groups.has(name)) groups.set(name, []);
    groups.get(name).push(p);
  }
  const temporary = path.join(root, "offline.tmp-" + process.pid),
    target = path.join(root, "offline");
  fs.rmSync(temporary, { recursive: true, force: true });
  fs.mkdirSync(temporary);
  const summary = { bundles: {} };
  try {
    for (const [name, files] of groups) {
      const parts = [
        "/* Generated by tools/build-offline.cjs. Do not edit; rebuild with npm run build:offline.\n * Byte-identical copies of the listed files for file:// use only. */\n",
        "window.FrontierOfflineAssets=window.FrontierOfflineAssets||{};\n",
      ];
      let bytes = 0;
      for (const p of files) {
        const data = fs.readFileSync(path.join(root, p));
        bytes += data.length;
        parts.push("window.FrontierOfflineAssets[" + JSON.stringify(p) + "]=" + JSON.stringify("data:" + MIME[path.extname(p).toLowerCase()] + ";base64," + data.toString("base64")) + ";\n");
      }
      fs.writeFileSync(path.join(temporary, name + ".js"), parts.join(""));
      summary.bundles[name] = { files: files.length, bytes };
    }
    fs.writeFileSync(path.join(temporary, "README.txt"), "Generated by tools/build-offline.cjs (npm run build:offline). Needed only to open index.html directly from disk. Safe to delete; not uploaded to Cloudflare.\n");
    fs.rmSync(target, { recursive: true, force: true });
    fs.renameSync(temporary, target);
  } catch (error) {
    fs.rmSync(temporary, { recursive: true, force: true });
    throw error;
  }
  return summary;
}

module.exports = { build, listAssets, groupRule };

if (require.main === module) {
  const summary = build(process.argv[2] || path.join(__dirname, ".."));
  for (const [name, info] of Object.entries(summary.bundles))
    console.log("offline/" + name + ".js: " + info.files + " files, " + (info.bytes / 1048576).toFixed(1) + " MB of assets");
}
